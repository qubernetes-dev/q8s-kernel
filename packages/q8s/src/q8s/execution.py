class ContainerImageValidator:
    """
    Validate that a container image exists in its registry.

    The image reference should be in the format:
    - 'user/repo:tag' for Docker Hub images
    - 'registry.com/user/repo:tag' for images in other registries

    Primarily, the image URL values are generated by `q8sctl build --init`
    command and stored in the `.q8s_cache/images` file. Images are built in CI pipelines.

    Args:
        image: Container image reference (e.g., 'user/repo:tag' or 'registry.com/user/repo:tag')
        registry_pat: Optional personal access token for registry authentication

    Returns:
        True if the image exists and is accessible

    Raises:
        ValueError: If the image is invalid, not found, or authentication fails
    """

    @staticmethod
    def validate(image: str, registry_pat: str | None = None) -> bool:
        if not image:
            raise ValueError("Container image must be a non-empty string")

        segments = image.split("/")
        if len(segments) < 2:
            raise ValueError(f"Invalid container image reference: {image}")

        if len(segments) == 3:
            registry_host = segments[0]
            repo_part = "/".join(segments[1:])
            username = segments[1]
        else:
            registry_host = "registry-1.docker.io"
            repo_part = "/".join(segments)
            username = segments[0]

        if ":" in repo_part:
            repository, tag = repo_part.split(":", 1)
        else:
            repository, tag = repo_part, "latest"

        try:
            dxf = DXF(registry_host, repo=repository)

            if registry_pat:
                dxf.authenticate(
                    username=username,
                    password=registry_pat,
                    actions=["pull"],
                )

            dxf.get_alias(tag)

        except DXFUnauthorizedError:
            raise ValueError(f"Container image '{image}' requires authentication")
        except requests.exceptions.HTTPError as e:
            if e.response is not None and hasattr(e.response, "status_code"):
                if e.response.status_code == 403:
                    raise ValueError(
                        f"Container image '{image}' requires authentication; invalid registry PAT"
                    )
                elif e.response.status_code == 404:
                    raise ValueError(f"Container image '{image}' not found")
            raise ValueError(f"Error validating container image '{image}': {str(e)}")

        return True


class K8sContext:
    container_image: str | None = None
    registry_pat: str | None = None
    target: str = "cpu"
    jm: pluggy.PluginManager = pluggy.PluginManager("q8s")

    def __init__(self, kubeconfig: str, progress: ProgressObserver | None = None):
        """
        Initialize the Kubernetes context.
        """
        self._progress = progress

        self.jm.add_hookspecs(JobTemplatePluginSpec)
        self._load_plugins()

        report_progress(progress, ProgressUpdate("cluster", "loading"))
        try:
            config.load_kube_config(kubeconfig)
            _, active_context = config.list_kube_config_contexts(config_file=kubeconfig)
            self.namespace = active_context.get("context", {}).get(
                "namespace", "default"
            )
            self.core_api_instance = client.CoreV1Api()
            self.batch_api_instance = client.BatchV1Api()
        except (Exception, KeyboardInterrupt) as error:
            status = "interrupted" if isinstance(error, KeyboardInterrupt) else "failed"
            report_progress(progress, ProgressUpdate("cluster", status))
            raise
        report_progress(
            progress, ProgressUpdate("cluster", "configured", self.namespace)
        )

        self.name = f"qubernetes-job-{K8sContext.get_id()}"

        self.__env = load_env()

    @staticmethod
    def get_id():
        """
        Generate a random ID.
        """
        return "".join(random.choices(string.ascii_lowercase + string.digits, k=6))

    def set_container_image(self, image: str):
        # ContainerImageValidator.validate(image, self.registry_pat)

        self.container_image = image

    def set_registry_pat(self, pat: str):
        self.registry_pat = pat

    def set_target(self, target):
        self.target = target

    def available_targets(self):
        return [
            p.target_name for p in self.jm.get_plugins() if hasattr(p, "target_name")
        ]

    def create_job_object(self, code: str) -> client.V1Job:
        return None

    def execute_workload(
        self, workload: Workload, submit: bool = False
    ) -> tuple[str, str]:
        """Execute the given workload."""
        run = _WorkloadRun(
            namespace=self.namespace,
            name_prefix=self.name,
            target=self.target,
            container_image=self.container_image,
            registry_pat=self.registry_pat,
            env=self.__env,
            core_api=self.core_api_instance,
            batch_api=self.batch_api_instance,
            hooks=self.jm.hook,
            progress=self._progress,
        )
        return run.execute(workload, submit)

    def _load_plugins(self):
        for ep in entry_points(group="q8s.targets"):
            plugin_cls = ep.load()
            plugin = plugin_cls()
            self.jm.register(plugin)
